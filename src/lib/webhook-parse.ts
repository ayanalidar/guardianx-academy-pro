import type { NextRequest } from "next/server"

/**
 * Shared plumbing for the two unauthenticated Google Apps Script webhooks
 * (/api/crm/webhook and /api/crm/batch-webhook).
 *
 * Why this exists: the first-generation scripts assumed a strict JSON body
 * with an exact field layout. Real-world Apps Scripts (and hand-edited ones)
 * post form-encoded payloads, forget the token header, or send the raw
 * `e.values` array from the form-submit trigger. Every one of those used to
 * bounce with a 400/401 and the lead was lost with only a server log line.
 * These helpers accept ALL of those shapes so capture "just works".
 */

export type LoosePayload = Record<string, unknown>

/**
 * Read the request body as JSON *or* urlencoded form data.
 * Returns null only when the body is empty or unparsable in both shapes.
 */
export async function parseBodyLoose(req: NextRequest): Promise<LoosePayload | null> {
  let raw = ""
  try {
    raw = await req.text()
  } catch {
    return null
  }
  if (!raw.trim()) return null
  // 1. JSON (the happy path for UrlFetchApp with contentType application/json)
  try {
    const parsed = JSON.parse(raw)
    if (parsed && typeof parsed === "object") return parsed as LoosePayload
  } catch {
    /* fall through to urlencoded */
  }
  // 2. application/x-www-form-urlencoded (Apps Script default when the
  //    payload is sent as an object without an explicit contentType)
  try {
    const params = new URLSearchParams(raw)
    const obj: LoosePayload = {}
    params.forEach((v, k) => {
      obj[k] = v
    })
    if (Object.keys(obj).length > 0) return obj
  } catch {
    /* ignore */
  }
  return null
}

/**
 * Webhook token from any of: body `token`, `x-webhook-token` header,
 * `?token=` query param. Scripts generated by us bake it into the body;
 * the alternates make hand-written scripts and curl debugging easy.
 */
export function extractWebhookToken(req: NextRequest, body: LoosePayload | null): string {
  const fromBody = typeof body?.token === "string" ? body.token : ""
  const fromHeader = req.headers.get("x-webhook-token") || ""
  const fromQuery = req.nextUrl?.searchParams?.get("token") || ""
  return (fromBody || fromHeader || fromQuery).trim()
}

const EMAIL_RE = /[^\s@]+@[^\s@]+\.[^\s@]+/
const LINKEDIN_RE = /linkedin\.com/i

/** Case/punctuation-insensitive key lookup ("WhatsApp Number" → "whatsappnumber"). */
function pick(obj: LoosePayload, keys: string[]): string {
  for (const k of Object.keys(obj)) {
    const norm = k.toLowerCase().replace(/[^a-z0-9]/g, "")
    if (keys.includes(norm)) {
      const v = obj[k]
      if (typeof v === "string" && v.trim()) return v.trim()
      if (typeof v === "number") return String(v)
    }
  }
  return ""
}

// Alias groups covering the common Google Form question titles.
const NAME_KEYS = ["name", "fullname", "yourname", "studentname", "candidatename", "leadname", "nameofthecandidate"]
const EMAIL_KEYS = ["email", "emailaddress", "mail", "youremail"]
const PHONE_KEYS = [
  "whatsapp", "whatsappnumber", "whatsappno", "whatsappnumberwithcountrycode",
  "phone", "phonenumber", "mobile", "mobileno", "contactnumber", "contact", "number",
]
const ORG_KEYS = ["organization", "organisation", "company", "college", "school", "university", "institution", "organizationname"]
const TYPE_KEYS = ["type", "leadtype", "organizationtype", "usertype", "iam"]
const REQ_KEYS = ["requirement", "requirements", "message", "notes", "query", "comment", "comments", "anythingelse", "additionaldetails"]
const BATCH_ID_KEYS = ["batchid"]
const BATCH_NAME_KEYS = ["batch", "batchname", "batchtitle", "cohort", "cohortname"]
const LINKEDIN_KEYS = ["linkedin", "linkedinprofile", "linkedinurl", "linkedinlink"]
const PROSTATUS_KEYS = ["professionalstatus", "currentprofessionalstatus", "status", "occupation"]
const JOBROLE_KEYS = ["jobrole", "currentjobrole", "currentjobroleordesignation", "designation", "role", "jobtitle"]

export interface NormalizedLead {
  name: string
  email: string
  phone: string
  organization: string
  type: string
  requirement: string
  batchId: string
  batchName: string
  linkedinProfile: string
  professionalStatus: string
  jobRole: string
}

/**
 * Normalize an arbitrary webhook payload into a lead-shaped object.
 * Handles: {token, lead:{...}} envelopes, flat form posts, and positional
 * `e.values` arrays (body.values / body.lead as array / raw array body).
 * Alias mapping runs first; a regex heuristic pass fills anything missing.
 */
export function normalizeLeadFields(body: LoosePayload): NormalizedLead {
  // Unwrap { lead: {...} } envelopes into one flat pool.
  let src: LoosePayload = body
  const leadField = body.lead
  if (leadField && typeof leadField === "object" && !Array.isArray(leadField)) {
    src = { ...body, ...(leadField as LoosePayload) }
  }

  // Positional arrays from onFormSubmit(e) → e.values
  const arr: unknown[] = Array.isArray(body.values)
    ? (body.values as unknown[])
    : Array.isArray(leadField)
      ? (leadField as unknown[])
      : Array.isArray(body)
        ? (body as unknown[])
        : []
  const strings = arr
    .filter((v): v is string => typeof v === "string" && !!v.trim())
    .map((s) => s.trim())

  const norm: NormalizedLead = {
    name: pick(src, NAME_KEYS),
    email: pick(src, EMAIL_KEYS),
    phone: pick(src, PHONE_KEYS),
    organization: pick(src, ORG_KEYS),
    type: pick(src, TYPE_KEYS),
    requirement: pick(src, REQ_KEYS),
    batchId: pick(src, BATCH_ID_KEYS),
    batchName: pick(src, BATCH_NAME_KEYS),
    linkedinProfile: pick(src, LINKEDIN_KEYS),
    professionalStatus: pick(src, PROSTATUS_KEYS),
    jobRole: pick(src, JOBROLE_KEYS),
  }

  // Heuristic pass over positional values (and any string fields) for
  // shapes the alias map didn't cover. Fill-only-if-empty keeps alias
  // matches authoritative.
  const leftovers: string[] = [...strings]
  for (const k of Object.keys(src)) {
    const v = src[k]
    if (typeof v === "string" && v.trim()) leftovers.push(v.trim())
  }
  for (const v of leftovers) {
    if (!norm.email && EMAIL_RE.test(v) && !v.includes(" ")) {
      const m = v.match(EMAIL_RE)
      if (m) { norm.email = m[0]; continue }
    }
    if (!norm.linkedinProfile && LINKEDIN_RE.test(v)) { norm.linkedinProfile = v; continue }
    const digits = v.replace(/[^0-9]/g, "")
    if (!norm.phone && digits.length >= 10 && digits.length <= 13) { norm.phone = v; continue }
    if (!norm.name && !EMAIL_RE.test(v) && digits.length <= 6 && v.length >= 2 && v.split(" ").length <= 4) {
      norm.name = v; continue
    }
    if (!norm.requirement && v.length >= 3 && v !== norm.name && v !== norm.phone && v !== norm.email) {
      norm.requirement = v
    }
  }

  return norm
}
